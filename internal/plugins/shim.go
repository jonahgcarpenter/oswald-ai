package plugins

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// ShimDirName is the per-profile directory holding generated bare-name
// wrappers for installed plugin CLIs. It lives alongside the per-plugin
// <name>/{code,data} trees so one fixed PATH entry
// (<profileRoot>/plugins/.bin) exposes every install. The model runs the bare
// tool name in terminal; the wrapper sets the per-plugin data HOME and execs
// the absolute target. Shims are derived cache: install/update/remove,
// install-deps, and boot repair regenerate them.
const ShimDirName = ".bin"

// PluginShimDir returns the per-profile shim directory:
// <profileRoot>/plugins/.bin.
func PluginShimDir(profileRoot string) string {
	return filepath.Join(ProfilePluginsDir(profileRoot), ShimDirName)
}

// RegenerateShims rebuilds the per-plugin shim directory from the current
// installs: one wrapper per resolvable plugin binary, stale wrappers pruned.
// Node sidecars resolve via the recorded manifest/metadata pin; manifest
// entry targets resolve under the plugin code tree. Collisions resolve
// deterministically: sorted plugin order, first name wins. It never logs
// paths, commands, or environment values, only counts and names.
func RegenerateShims(profileRoot string) error {
	if strings.TrimSpace(profileRoot) == "" {
		return fmt.Errorf("plugin home is unavailable")
	}
	winners := ScanProfileWinners(profileRoot)
	keys := make([]string, 0, len(winners))
	for key := range winners {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	type shim struct {
		name   string
		target string
		owner  string
	}
	wanted := map[string]shim{}
	for _, key := range keys {
		manifest := winners[key]
		name, target, ok := resolveShimTarget(profileRoot, key, manifest)
		if !ok {
			continue
		}
		if existing, taken := wanted[name]; taken {
			_ = existing
			continue
		}
		wanted[name] = shim{name: name, target: target, owner: key}
	}

	dir := PluginShimDir(profileRoot)
	if err := os.MkdirAll(dir, 0700); err != nil {
		return fmt.Errorf("prepare plugin shims: %w", err)
	}
	_ = os.Chmod(dir, 0700)

	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("read plugin shims: %w", err)
	}
	for _, entry := range entries {
		if _, ok := wanted[entry.Name()]; !ok {
			_ = os.Remove(filepath.Join(dir, entry.Name()))
		}
	}

	wrote := 0
	for name, s := range wanted {
		home := filepath.Join(PluginDataDir(profileRoot, s.owner), "home")
		if err := os.MkdirAll(home, 0700); err != nil {
			return fmt.Errorf("prepare plugin home: %w", err)
		}
		_ = os.Chmod(home, 0700)
		content := "#!/bin/sh\n# Generated by oswald plugins - do not edit.\nHOME=" + shellQuote(home) + " export HOME\nmkdir -p \"$HOME\" 2>/dev/null\nexec " + shellQuote(s.target) + " \"$@\"\n"
		path := filepath.Join(dir, name)
		if current, err := os.ReadFile(path); err == nil && string(current) == content {
			continue
		}
		if err := os.WriteFile(path, []byte(content), 0700); err != nil {
			return fmt.Errorf("write plugin shim: %w", err)
		}
		_ = os.Chmod(path, 0700)
		wrote++
	}
	_ = wrote
	return nil
}

// resolveShimTarget maps one installed plugin to its bare shim name and
// absolute target. Node sidecars win; otherwise a relative manifest entry
// under the code tree is used. Unknown or unverifiable binaries are skipped
// so lockfile-only installs without a known bin create no shim.
func resolveShimTarget(profileRoot, key string, manifest Manifest) (name, target string, ok bool) {
	meta, _ := ReadInstallMetadata(profileRoot, key)
	if bin := EffectiveNodeBin(manifest, meta, ""); bin != "" {
		if resolved, err := NodeBinPath(profileRoot, key, bin); err == nil {
			return bin, resolved, true
		}
		return "", "", false
	}
	entry := strings.TrimSpace(manifest.Entry)
	if entry == "" {
		return "", "", false
	}
	if filepath.IsAbs(entry) || entry != filepath.Clean(entry) {
		return "", "", false
	}
	for _, part := range strings.Split(filepath.ToSlash(entry), "/") {
		if part == "" || part == "." || part == ".." {
			return "", "", false
		}
	}
	candidate := filepath.Join(PluginCodeDir(profileRoot, key), filepath.FromSlash(entry))
	info, err := os.Lstat(candidate)
	if err != nil || !info.Mode().IsRegular() {
		return "", "", false
	}
	if info.Mode().Perm()&0111 == 0 {
		return "", "", false
	}
	if rel, err := filepath.Rel(PluginCodeDir(profileRoot, key), candidate); err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", "", false
	}
	return key, candidate, true
}

// shellQuote renders one path as a POSIX single-quoted word.
func shellQuote(path string) string {
	return "'" + strings.ReplaceAll(path, "'", "'\\''") + "'"
}

// shimStats is a test seam reporting the current shim set.
func shimStats(profileRoot string) (names []string, err error) {
	entries, err := os.ReadDir(PluginShimDir(profileRoot))
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		names = append(names, entry.Name())
	}
	sort.Strings(names)
	return names, nil
}
